// Generate Lots for Developments
const generateLotsForBlock = (
  devId: string,
  blockName: string,
  startNum: number,
  count: number,
  basePrice: number,
  area: number
): Lot[] => {
  const statuses: ("Disponivel" | "Reservado" | "Em Proposta" | "Vendido" | "Bloqueado")[] = [
    "Disponivel",
    "Disponivel",
    "Vendido",
    "Disponivel",
    "Reservado",
    "Vendido",
    "Em Proposta",
    "Disponivel",
    "Vendido",
    "Disponivel",
    "Vendido",
    "Disponivel",
  ];

  return Array.from({ length: count }, (_, i) => {
    const num = startNum + i;
    const status = statuses[i % statuses.length];
    const lotNumStr = num < 10 ? `0${num}` : `${num}`;
    const lotPrice = basePrice + (i % 3) * 15000;
    const lotArea = area + (i % 4) * 25;

    return {
      id: `lot-${devId}-${blockName.replace(/\s+/g, "")}-${lotNumStr}`,
      developmentId: devId,
      block: blockName,
      lotNumber: `Lote ${lotNumStr}`,
      areaM2: lotArea,
      basePrice: lotPrice,
      promotionalPrice: status === "Disponivel" && i % 4 === 0 ? lotPrice * 0.95 : undefined,
      minDownPayment: Math.round(lotPrice * 0.1), // 10% entrada
      maxInstallments: 120, // até 120 meses
      status: status,
      reservedByClientName:
        status === "Reservado"
          ? "Investidor Anônimo / Privativo"
          : status === "Em Proposta"
            ? "Eng. Ricardo Albuquerque"
            : undefined,
      reservedByBrokerName:
        status === "Reservado" || status === "Em Proposta" ? "Fernando Albuquerque" : undefined,
      reservedAt:
        status === "Reservado" ? "2026-08-14" : status === "Em Proposta" ? "2026-08-15" : undefined,
      simulation: {
        downPayment: Math.round(lotPrice * 0.1),
        installments: 60,
        installmentValue: Math.round(((lotPrice * 0.9) / 60) * 1.06),
        interestRateAnnual: 8.5,
      },
    };
  });
};

